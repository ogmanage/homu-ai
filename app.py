import streamlit as st

from core.auth import require_auth

st.set_page_config(
    page_title="法務AI",
    page_icon="⚖️",
    layout="wide",
    initial_sidebar_state="expanded",
)

require_auth()

# ─── Landing page ────────────────────────────────────────────────────────────

st.title("⚖️ 法務AI — 法律文書支援システム")
st.markdown(
    """
    企業法務担当者レベルの**契約書作成・レビュー**をAIがサポートします。

    > **免責事項**: 本ツールの出力は参考情報です。弁護士の法的判断を代替するものではありません。
    > 重要な契約の締結前には必ず法律専門家にご確認ください。
    """
)

st.divider()

col1, col2, col3 = st.columns(3, gap="large")

with col1:
    st.markdown("### 📝 契約書作成")
    st.markdown(
        """
        10種類の契約書を自動生成します。
        - NDA / 業務委託 / SES / 準委任 / 請負
        - 利用規約 / 売買 / パートナー / 業務提携 / 雇用

        基本情報を入力するだけで完成版のドラフトを出力。
        Word・PDF形式でダウンロード可能。
        """
    )
    st.page_link("pages/1_契約書作成.py", label="契約書を作成する →", icon="📝")

with col2:
    st.markdown("### 🔍 契約書レビュー")
    st.markdown(
        """
        既存の契約書をアップロードしてリスク分析します。
        - 総合評価グレード（A〜E）
        - リスク項目の一覧（高・中・低）
        - 修正案を条文テキストで提示
        - 法的根拠（条文番号）を明示

        PDF・Word・テキスト形式に対応。
        """
    )
    st.page_link("pages/2_契約書レビュー.py", label="契約書をレビューする →", icon="🔍")

with col3:
    st.markdown("### 🔄 契約書比較")
    st.markdown(
        """
        旧版と新版の契約書を比較します。
        - 追加・削除・変更された条項を一覧表示
        - 各変更の法的影響を説明
        - 自社に不利な変更点を強調表示
        - 全体的なリスク評価を提供

        改訂前後の契約書を2ファイルアップロード。
        """
    )
    st.page_link("pages/3_契約書比較.py", label="契約書を比較する →", icon="🔄")

st.divider()

